// Overlays the community areas of each proposed Expanded Mental Health
// Services Program area (scripts/chicago-referendum-areas.ts) on the 2025
// Chicago precincts, by Cook County address points, and prints the precincts
// whole inside and on the edge. Reports differences from the committed lists;
// `--write` replaces them. Needs data:fetch (chicago-community-areas,
// chicago-precincts, address points).
// Run: node scripts/build-chicago-referendum-areas.ts [--write]

import { execFileSync } from 'node:child_process'
import { readFile, writeFile } from 'node:fs/promises'
import { findContaining } from '../src/shared/geo.ts'
import {
  PRECINCTS,
  REFERENDUM_AREAS,
  WHOLE_SHARE,
} from './chicago-referendum-areas.ts'
import { chicagoPoints } from './lib/chicago.ts'
import { loadBoundary, toAreas } from './lib/layers.ts'

const FILE = new URL('./chicago-referendum-areas.ts', import.meta.url).pathname

const communities = toAreas(
  await loadBoundary('chicago-community-areas'),
  (p) => String(p.community),
)
const points = await chicagoPoints([])

// Precinct → address points, and points per community area.
const counts = new Map<string, Map<string, number>>()
for (const p of points) {
  const community = findContaining(communities, p.point)[0] ?? ''
  const byArea = counts.get(p.precinct) ?? new Map<string, number>()
  byArea.set(community, (byArea.get(community) ?? 0) + 1)
  counts.set(p.precinct, byArea)
}

const order = (a: string, b: string) => {
  const [wa, pa] = a.split('-').map(Number)
  const [wb, pb] = b.split('-').map(Number)
  return wa - wb || pa - pb
}

const lists: typeof PRECINCTS = {}
let changed = false
for (const area of REFERENDUM_AREAS) {
  const whole: string[] = []
  const edge: Record<string, number> = {}
  for (const key of [...counts.keys()].sort(order)) {
    const byArea = counts.get(key)!
    const total = [...byArea.values()].reduce((a, b) => a + b, 0)
    const inside = area.communityAreas.reduce(
      (n, c) => n + (byArea.get(c) ?? 0),
      0,
    )
    if (!inside) continue
    const share = inside / total
    if (share >= WHOLE_SHARE) whole.push(key)
    else edge[key] = Math.round(share * 1000) / 1000
  }
  lists[area.name] = { whole, edge }
  console.log(
    `${area.name}: ${whole.length} whole precincts, ${Object.keys(edge).length} edge precincts`,
  )
  for (const [key, share] of Object.entries(edge))
    console.log(
      `  edge ${key}: ${(share * 100).toFixed(1)}% of address points inside`,
    )
  const old = PRECINCTS[area.name]
  if (JSON.stringify(old) !== JSON.stringify(lists[area.name])) {
    changed = true
    console.log(`  differs from the committed list`)
  }
}

if (process.argv.includes('--write')) {
  const source = await readFile(FILE, 'utf8')
  const block = [
    '// BEGIN GENERATED by `node scripts/build-chicago-referendum-areas.ts --write`',
    'export const PRECINCTS: Record<',
    '  string,',
    '  { whole: string[]; edge: Record<string, number> }',
    `> = ${JSON.stringify(lists)}`,
    '// END GENERATED',
  ].join('\n')
  const next = source.replace(
    /\/\/ BEGIN GENERATED[\s\S]*?\/\/ END GENERATED/,
    block,
  )
  await writeFile(FILE, next)
  execFileSync('npx', ['prettier', '--write', FILE], { stdio: 'inherit' })
  console.log(`Wrote ${FILE}`)
} else if (changed) {
  console.log('Run with --write to update scripts/chicago-referendum-areas.ts')
  process.exitCode = 1
}
