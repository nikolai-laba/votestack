// Downloads Los Angeles County's address points (CAMS, LA County eGIS) into
// data/raw/la/cams.csv, and writes data/raw/la/address-points.tsv in the same
// format as Cook County's for the local geocoder. The County's terms allow
// copying and adapting the data (see data/README.md).
// Run: node scripts/la/fetch-la-address-points.ts [--skip-download]

import { createWriteStream, existsSync } from 'node:fs'
import { mkdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { Readable } from 'node:stream'
import { pipeline } from 'node:stream/promises'
import { RAW, ROOT, getJson } from '../lib/data.ts'
import { csvRows } from './csv.ts'
import { statePlaneZone5ToLatLng } from './state-plane.ts'

const ITEM = 'ed1937ab15214b5d937ef4fe4cb55f44'
const DIR = join(RAW, 'la')
const CSV = join(DIR, 'cams.csv')

/** The Hub prepares the export on request; poll until it's ready. */
async function exportUrl(): Promise<string> {
  for (let attempt = 0; attempt < 60; attempt++) {
    const status = await getJson<{ status: string; resultUrl?: string }>(
      `https://hub.arcgis.com/api/download/v1/items/${ITEM}/csv?redirect=false&layers=0`,
    )
    if (status.status === 'Completed' && status.resultUrl)
      return status.resultUrl
    await new Promise((r) => setTimeout(r, 10_000))
  }
  throw new Error('The address point export did not finish in 10 minutes')
}

await mkdir(DIR, { recursive: true })
if (!process.argv.includes('--skip-download') || !existsSync(CSV)) {
  const url = await exportUrl()
  const res = await fetch(url, {
    headers: { 'User-Agent': 'VoteStack data import (votestack.org)' },
  })
  if (!res.ok || !res.body) throw new Error(`${res.status} for ${url}`)
  await pipeline(
    Readable.fromWeb(res.body as import('node:stream/web').ReadableStream),
    createWriteStream(CSV),
  )
}

const lines: string[] = []
const cities = new Set<string>()
let skipped = 0
for await (const row of csvRows(CSV)) {
  const number = row.Number?.trim()
  const street = row.StreetName?.trim()
  // The export's x and y are State Plane feet.
  const x = Number(row.x)
  const y = Number(row.y)
  if (!number || !street || !x || !y) {
    skipped++
    continue
  }
  const { lat, lng } = statePlaneZone5ToLatLng(x, y)
  // Street from its parts, without units: "1200 N AVENUE 64" or
  // "200 N SPRING STREET". Full street types ("WAY", not the County's "WY"),
  // which the parser reads the same way voters type them.
  const address = [
    number,
    row.PreDirAbbr || row.PreDir,
    row.PreType,
    street,
    row.PostType,
    row.PostDirAbbr || row.PostDir,
  ]
    .map((s) => s?.trim())
    .filter(Boolean)
    .join(' ')
    .toUpperCase()
  const city = (row.PostComm1 || row.LegalComm || '').trim().toUpperCase()
  for (const c of [row.PostComm1, row.PostComm2, row.PostComm3, row.LegalComm])
    if (c?.trim() && !/^unincorporated$/i.test(c.trim()))
      cities.add(c.trim().toUpperCase())
  lines.push(
    [
      address,
      city,
      (row.ZipCode ?? '').trim(),
      lat.toFixed(6),
      lng.toFixed(6),
    ].join('\t'),
  )
}

await writeFile(
  join(DIR, 'address-points.tsv'),
  `address\tcity\tzip\tlat\tlng\n${lines.join('\n')}\n`,
)
// Postal and legal city names, so the parser can find a city typed without a comma.
await writeFile(
  join(ROOT, 'src/shared/la-cities.ts'),
  `// Generated by scripts/la/fetch-la-address-points.ts from LA County CAMS
// address points (postal and legal community names). Don't edit by hand.

export const LA_CITIES: ReadonlySet<string> = new Set(${JSON.stringify([...cities].sort(), null, 2)})
`,
)
console.log(`${lines.length} address points (${skipped} skipped)`)
