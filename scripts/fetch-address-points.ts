// Downloads Cook County Address Points (public domain) into
// data/raw/address-points.tsv for the local geocoder.
// Run: node scripts/fetch-address-points.ts

import { mkdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { RAW, ROOT, socrataRows } from './lib/data.ts'

interface Row {
  cmpaddabrv?: string
  post_comm?: string
  post_code?: string
  lat?: string
  long?: string
}

// The full address string is the reliable field; the separate house-number
// column doesn't always match it.
const rows = await socrataRows<Row>(
  'datacatalog.cookcountyil.gov',
  '78yw-iddh',
  {
    $select: 'cmpaddabrv,post_comm,post_code,lat,long',
    $where: 'lat IS NOT NULL',
  },
)

const lines = rows
  .filter((r) => r.cmpaddabrv && r.lat && r.long)
  .map((r) =>
    [r.cmpaddabrv, r.post_comm ?? '', r.post_code ?? '', r.lat, r.long].join(
      '\t',
    ),
  )

await mkdir(RAW, { recursive: true })
await writeFile(
  join(RAW, 'address-points.tsv'),
  `address\tcity\tzip\tlat\tlng\n${lines.join('\n')}\n`,
)
// Postal city names, so the parser can find a city typed without a comma.
const cities = [
  ...new Set(lines.map((l) => l.split('\t')[1]).filter(Boolean)),
].sort()
await writeFile(
  join(ROOT, 'src/shared/cook-cities.ts'),
  `// Generated by scripts/fetch-address-points.ts from Cook County Address Points
// (postal city names, which aren't always the municipality). Don't edit by hand.

export const COOK_CITIES: ReadonlySet<string> = new Set(${JSON.stringify(cities, null, 2)})
`,
)

console.log(
  `${lines.length} address points (${rows.length - lines.length} skipped)`,
)
