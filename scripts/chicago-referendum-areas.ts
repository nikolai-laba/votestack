/** The district for a "To the Voters of …:" scope naming a program area, or null. */
export function referendumAreaDistrict(scope: string): OcdId | null {
  const name = scope.match(
    /^the proposed (.+) Expanded Mental Health Services Program Area$/,
  )?.[1]
  return REFERENDUM_AREAS.find((a) => a.name === name)?.districtId ?? null
}

/** Adds the program areas a precinct ("ward-precinct") is in to each of its splits. */
export function withReferendumAreas(
  key: string,
  splits: ClerkSplit[],
): ClerkSplit[] {
  const added: LayerDistrict[] = REFERENDUM_AREAS.flatMap(
    (a): LayerDistrict[] =>
      a.whole.includes(key)
        ? [{ ocdId: a.districtId, layer: REFERENDUM_AREA_LAYER }]
        : key in a.edge
          ? [
              {
                ocdId: a.districtId,
                layer: REFERENDUM_AREA_LAYER,
                possible: true,
              },
            ]
          : [],
  )
  if (!added.length) return splits
  return splits.map((s) => ({ ...s, districts: [...s.districts, ...added] }))
}
