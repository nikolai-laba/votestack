/** The layer name the areas get in precinct splits. */
export const REFERENDUM_AREA_LAYER = 'expanded mental health services program'

/** Share of a precinct's address points inside an area to count as whole. */
export const WHOLE_SHARE = 0.99

export interface ReferendumArea {
  /** As in the Board's "the proposed <name> Expanded Mental Health Services Program Area". */
  name: string
  /** Minted. */
  districtId: OcdId
  /** City of Chicago community areas (igwz-8jzy `community`), per the organizers. */
  communityAreas: string[]
  /** "ward-precinct" keys with at least WHOLE_SHARE of address points inside. */
  whole: string[]
  /** Edge precincts: "ward-precinct" → share of address points inside. */
  edge: Record<string, number>
}

/** Minted. "Mid-Northside" → `…/place:chicago/expanded_mental_health_services_program:mid_northside` */
const program = (name: string): OcdId =>
  `${CHICAGO}/expanded_mental_health_services_program:${name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')}`

