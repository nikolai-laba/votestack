// Chicago ballot questions whose territory the Board of Election Commissioners
// doesn't publish by precinct (2026-10-11): the proposed Mid-Northside and
// Far Southwest Side Expanded Mental Health Services Program areas, two
// questions each (establishing the program, and its 2027 tax extension).
// Used by import-chicago-boe.ts (the questions' district) and
// build-chicago-precincts.ts (the precincts that get it).
//
// Source: the Board's candidate list names only "the proposed … Program Area";
// 405 ILCS 22/15 requires just "a description of the territory", and the Board
// publishes no precinct list or per-precinct sample ballot for these. The only
// territory available is the organizers' description by community area
// (saveourmentalhealth.org, "Current and Upcoming EMHSPs"), so each area here
// is that set of City of Chicago community areas (data portal igwz-8jzy),
// overlaid on the 2025 precincts by Cook County address points
// (scripts/build-chicago-referendum-areas.ts, run 2026-10-11):
// - a precinct with at least 99% of its address points inside gets the
//   questions;
// - a precinct with some but fewer inside is an edge precinct: the questions
//   are shown as possibly on the ballot (LayerDistrict.possible), because the
//   petition's exact boundary isn't public.
// Backtest: the same method on the 2024 Englewood–Greater Chatham and Near
// Southwest Side questions (2023–24 precincts) matched the Board's 2024
// per-precinct results in 91 of 93 and 59 of 61 precincts; the misses were
// edge precincts both ways, plus one precinct fully inside that had no
// question. Replace these lists
// with the Board's own if it publishes them, and check them against its
// November results.

import type { OcdId } from '../src/shared/ballot.ts'
